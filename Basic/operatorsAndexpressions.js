// Arithmetic Operators
let a = 10
let b = 20
console.log("a+b =", a+b)
console.log("a-b =", a-b)
console.log("a/b =", a/b)
console.log("a%b =", a%b)
console.log("a*b =", a*b)
console.log("a**b =", a**b)
console.log("++a =", ++a )
console.log("a++ =", a++ )
console.log("--a =", --a )
console.log("a-- =", a-- )

//Assignment Operators
let c = 30
c += 10 // c = c + 10
c -= 10 // c = c - 10
c *= 10 // c = c * 10
c /= 10 // c = c / 10
c %= 10 // c = c % 10
c **= 10 // c = c ** 10
console.log(c);

//Comparison operators
let d = 10
let e = 11
console.log("d == e =", d == e)
console.log("d != e =", d != e)
console.log("d === e =", d === e)
console.log("d !== e =", d !== e)
console.log("d > e =", d > e)
console.log("d < e =", d < e)
console.log("d >= e =", d >= e)
console.log("d <= e =", d <= e)

//Logical Operators 
let f = 20
let g = 21
console.log("f>g && f==g =", f>g && f==g)
console.log("f>g || f==g =", f>g || f==g)
console.log("!true =", !true)